/**
 * 统一的金额取整口径 —— 迁移脚本 / 服务端 / 前端必须共用同一套实现。
 *
 * 为什么连 1 分钱都要较真：
 * `Math.round(x * 100) / 100` 与 `r2(x)` 在边界值上会得到不同结果。
 * 例：1.005 在计算机里的真实值是 1.00499999999999989…，直接乘 100 得 100.4999…，
 *     截断口径舍到 100 → ¥1.00；带纠偏后舍到 101 → ¥1.01。
 * 这些值并非刻意构造出来的：`(总额 - 已付)`、`(本次收取 - 剩余额度)` 这类中间量，
 * 天然会产生非整分的结果。
 *
 * 单独看无害，但一旦两边口径不一致 —— 比如启动时的自愈迁移用「截断」口径写库、
 * 运行时查询却用另一口径读出来展示 —— 同一笔账就会出现
 * 「库里躺着 ¥1.00、页面算成 ¥1.01」的对不上。差额小到日常根本发现不了，
 * 往往要等逐笔对账到分时才暴露。
 *
 * 所以：凡金额一律走 r2，绝不再写内联的 `Math.round(x * 100) / 100`。
 *
 * 注意：前端 public/js/app.js 里有一份等价实现（浏览器无法 require 本文件）。
 *      改这里的算法时，必须同步改前端那份，并在注释里说明。
 *
 * ── 算法为什么写成这样（两个坑，缺一不可）────────────────────────────
 * 坑一：纠正量的量级必须与数值本身成正比。
 *       曾经写成 `Math.round((v + Number.EPSILON) * 100) / 100`（加一个绝对常量），
 *       它对 1.005 有效，但 v 一旦超过 2，`Number.EPSILON` 已经小于 v 的 1 个 ULP，
 *       加上去毫无作用，补偿静默失效 —— 属于「碰巧正确」，换个位数就崩。
 *       这里改成 `v * (1 + Number.EPSILON * 4)`：double 乘 100 引入的相对误差约 1e-16，
 *       抬 4 倍足以跨越 .5 判定边界，又远小于最小金额单位（半分），
 *       不会把本该舍去的 0.0049 抬成 0.01。
 *
 * 坑二：Math.round 对负数不是四舍五入，而是向 +∞ 靠拢。
 *       Math.round(-0.5) === -0（而不是 -1），Math.round(-100.5) === -100。
 *       于是 -1.005 会得到 -1.00、-0.145 得到 -0.14 —— 与正数的方向和结果都不对称。
 *       60 万个三位小数样本（含正负）里，不对称实现会错 3 万个（恰好是全部负样本的一半）。
 *       这里取绝对值计算后再补回符号，正负数进位方向对称，符合「四舍五入」的直觉。
 *
 * 非有限值（NaN / Infinity）原样返回，不在这里抹成 0：
 * 一旦抹平，脏数据就会被静默洗白，反而查不出是哪个环节算出来的。
 */

/** 四舍五入到分（对称半进位 + 与量级成正比的浮点纠偏） */
const r2 = (n) => {
  const v = Number(n);
  if (!Number.isFinite(v)) return v;
  const sign = v < 0 ? -1 : 1;
  return sign * Math.round(Math.abs(v) * (1 + Number.EPSILON * 4) * 100) / 100;
};

module.exports = { r2 };
